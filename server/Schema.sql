CREATE TABLE users (
  id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR2(100) NOT NULL,
  email     VARCHAR2(150) NOT NULL UNIQUE,
  password  VARCHAR2(100) NOT NULL,
  phone     VARCHAR2(20),
  role      VARCHAR2(10)  NOT NULL CHECK (role IN ('owner', 'workshop'))
);

CREATE TABLE cars (
  id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id     NUMBER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  make         VARCHAR2(50) NOT NULL,
  model        VARCHAR2(50) NOT NULL,
  year         NUMBER(4),
  plate_number VARCHAR2(15) NOT NULL UNIQUE,
  mileage      NUMBER DEFAULT 0,
  photo_url    VARCHAR2(500)
);

CREATE TABLE workshops (
  id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    NUMBER NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
  name       VARCHAR2(100) NOT NULL,
  address    VARCHAR2(200),
  latitude   NUMBER(9,6),
  longitude  NUMBER(9,6),
  avg_rating NUMBER(3,1) DEFAULT 0
);

CREATE TABLE services (
  id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workshop_id  NUMBER NOT NULL REFERENCES workshops(id) ON DELETE CASCADE,
  name         VARCHAR2(100) NOT NULL,
  price        NUMBER(8,2),
  duration_min NUMBER
);

CREATE TABLE appointments (
  id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  car_id          NUMBER NOT NULL REFERENCES cars(id),
  workshop_id     NUMBER NOT NULL REFERENCES workshops(id),
  service_id      NUMBER NOT NULL REFERENCES services(id),
  scheduled_at    TIMESTAMP NOT NULL,
  status          VARCHAR2(15) DEFAULT 'pending' NOT NULL
                  CHECK (status IN ('pending', 'confirmed', 'completed', 'cancelled')),
  notes           VARCHAR2(1000),
  issue_photo_url VARCHAR2(500)
);

CREATE TABLE reviews (
  id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  appointment_id NUMBER NOT NULL UNIQUE REFERENCES appointments(id),
  rating         NUMBER(1) NOT NULL CHECK (rating BETWEEN 1 AND 5),
  comment_text   VARCHAR2(1000)
);

CREATE OR REPLACE TRIGGER trg_reviews_rating
AFTER INSERT OR UPDATE OR DELETE ON reviews
BEGIN
  UPDATE workshops w
  SET avg_rating = NVL((
        SELECT ROUND(AVG(r.rating), 1)
        FROM reviews r
        JOIN appointments a ON a.id = r.appointment_id
        WHERE a.workshop_id = w.id), 0);
END;
